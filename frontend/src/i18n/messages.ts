function buildLocale(base: MessageMap, overrides: Partial<MessageMap>): MessageMap {
  const out: MessageMap = { ...base };
  for (const [k, v] of Object.entries(overrides)) {
    if (v !== undefined) out[k] = v;
  }
  for (const id of NAV_IDS) {
    const navKey = `nav.${id}`;
    out[navKey] = overrides[id] ?? base[id] ?? EN[id] ?? id;
  }
  for (const id of PAGE_IDS) {
    const subKey = `page.${id}.subtitle`;
    if (!out[subKey] && EN[subKey]) out[subKey] = EN[subKey];
  }
  return out;
}

export const messages: Record<LocaleCode, MessageMap> = {
  en: buildLocale(EN, {}),
  es: buildLocale(EN, ES),
  de: buildLocale(EN, DE),
};

export function translate(locale: LocaleCode, key: string): string {
  return messages[locale][key] ?? messages.en[key] ?? key;
}

export function navLabel(locale: LocaleCode, id: string, fallback: string): string {
  return translate(locale, `nav.${id}`) || fallback;
}

export function pageTitle(locale: LocaleCode, pageId: string, fallback: string): string {
  const navId = pageTitleKey(pageId);
  const fromNav = translate(locale, `nav.${navId}`);
  if (fromNav !== `nav.${navId}`) return fromNav;
  const direct = translate(locale, pageId);
  if (direct !== pageId) return direct;
  return fallback;
}

export function pageSubtitle(locale: LocaleCode, pageId: string, fallback?: string): string | undefined {
  const key = `page.${pageId}.subtitle`;
  const val = translate(locale, key);
  if (val !== key) return val;
  return fallback;
}
